// Package identitystore 持久化单代理身份并保守处理注册响应丢失
//
// 调用者必须显式启用此功能，提供独立于实际构建工作区的绝对私有目录，
// 并将实际验证过的控制端传输配置绑定到 ControllerBinding
// 本包不建立连接，不读取注册令牌，不轮换凭据，也不自动重置恢复证据
//
// 注册前先持久化无令牌的 pending 记录及保护标记；收到有效响应后将 ready
// 记录写入独占临时文件，依次同步文件、原子重命名和同步目录，最后移除保护标记
// 标记删除只发生在 ready 已完成同步之后；即使最后一次目录同步遇到物理故障，
// 重启也只可能恢复原身份或因残留标记拒绝启动，不会把 ready 当成空状态再次注册
// 任意失败都会阻止当前实例继续注册，不会删除模糊的待定状态
//
// 权限检查隔离其他系统用户和意外暴露，不抵御 root、同 UID 的恶意进程、
// 管理员创建的构建工作区挂载别名，或拥有同一身份权限的非隔离构建任务
// 需要提供具有可靠原子重命名、文件同步、目录同步和进程锁语义的本地文件系统
package identitystore
